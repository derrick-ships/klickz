import { test, expect } from "@playwright/test";
test("brand decoration plays one finite take without playback controls", async ({ page }) => {
  await page.goto("/?mode=generate");
  const scene = page.locator('[data-brand-scene="signal"]');
  await expect(scene.locator("img")).toHaveJSProperty("naturalWidth", 1344);
  await expect(scene.getByRole("button")).toHaveCount(0);
  const player = scene.locator("video");
  await expect(player).toHaveJSProperty("loop", false);
  await expect.poll(() => player.evaluate(v => (v as HTMLVideoElement).currentTime)).toBeGreaterThan(.05);
  await expect(scene).toHaveAttribute("data-motion", "playing");
  await expect(scene).toHaveAttribute("data-motion", "still", { timeout: 6000 });
  expect(await player.evaluate(v => (v as HTMLVideoElement).paused)).toBe(true);
  expect(await player.evaluate(v => (v as HTMLVideoElement).currentTime)).toBeLessThan(5);
});
test("brand motion settles when editing or motion preference changes", async ({ page }) => {
  await page.goto("/?mode=generate");
  const scene = page.locator('[data-brand-scene="signal"]');
  await expect(scene).toHaveAttribute("data-motion", "playing");
  await page.getByLabel("Prompt", { exact: true }).focus();
  await expect(scene).toHaveAttribute("data-motion", "still");
  expect(await scene.locator("video").evaluate(v => (v as HTMLVideoElement).paused)).toBe(true);
  await page.goto("/connect");
  const onboarding = page.locator('[data-brand-scene="aperture"]');
  await expect(onboarding).toHaveAttribute("data-motion", "playing");
  await page.emulateMedia({ reducedMotion: "reduce" });
  await expect(onboarding).toHaveAttribute("data-motion", "still");
  expect(await onboarding.locator("video").evaluate(v => (v as HTMLVideoElement).paused)).toBe(true);
});
test("reduced-motion and data-saving visitors load only the poster", async ({ page }) => {
  await page.emulateMedia({ reducedMotion: "reduce" });
  await page.setViewportSize({ width: 390, height: 844 });
  const videos: string[] = [];
  page.on("request", r => { if (/\/brand\/.*\.(webm|mp4)/.test(r.url())) videos.push(r.url()); });
  await page.goto("/connect");
  const scene = page.locator('[data-brand-scene="aperture"]');
  await expect(scene.locator("img")).toHaveJSProperty("naturalWidth", 1344);
  await expect(scene.locator("source")).toHaveCount(0);
  expect(videos).toHaveLength(0);
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(390);
  await page.screenshot({ path: "evidence/openpikzels-brand-onboarding-mobile.png", fullPage: true });
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.screenshot({ path: "evidence/openpikzels-brand-onboarding-desktop.png", fullPage: true });
  await page.emulateMedia({ reducedMotion: "no-preference" });
  await page.addInitScript(() => Object.defineProperty(navigator, "connection", { value: { saveData: true, addEventListener() {}, removeEventListener() {} }, configurable: true }));
  await page.reload();
  await expect(scene.locator("img")).toHaveJSProperty("naturalWidth", 1344);
  await expect(scene.locator("source")).toHaveCount(0);
  expect(videos).toHaveLength(0);
});
