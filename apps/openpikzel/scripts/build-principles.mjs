// Generates src/lib/principles.generated.ts from principles/*.md, a verbatim copy of
// Derrick's thumbnail-playbook.zip (files 00-10). The mediator treats only this text as principles.
import { readdir, readFile, writeFile } from "node:fs/promises";
const dir = new URL("../principles/", import.meta.url);
const files = (await readdir(dir)).filter((f) => /^\d\d-.*\.md$/.test(f)).sort();
const parts = [];
for (const f of files) parts.push("=== " + f + " ===\n" + (await readFile(new URL(f, dir), "utf8")).trim());
await writeFile(
  new URL("../src/lib/principles.generated.ts", import.meta.url),
  "// Generated by scripts/build-principles.mjs from principles/*.md (thumbnail-playbook.zip). Do not edit.\n" +
    "export const principleFiles = " + JSON.stringify(files) + ";\n" +
    "export const principles = " + JSON.stringify(parts.join("\n\n")) + ";\n",
);
console.log("principles.generated.ts written from", files.length, "files");
